#!/usr/bin/env python3
"""Package built plugins into <workspace>/.build/docs and write plugins.json.

Input:  plugins/<id>/manifest.json + <workspace>/.temp/plugin-dist/<id>/
Output: <workspace>/.build/docs/<id>_<version>.zip
        <workspace>/.build/docs/plugins.json
        <repo>/plugins.json (same catalog, source copy)

Each ZIP carries the plugin's own `README.md` / `LICENSE`, a generated
`LICENSE-NOTICE.md` (license + where the source for this version lives) and a
generated `THIRD-PARTY-NOTICES.md` (the per-package license table).
"""
from __future__ import annotations

import hashlib
import json
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
# 依赖解析复用**门禁那一份**：在这里再写一遍 `cargo metadata` 就是第二真源，两份迟早漂，
# 而漂了的那一份恰好是打进用户手里的东西。
from check_licenses import metadata as cargo_metadata  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
WORKSPACE = ROOT.parent
PLUGINS = ROOT / "plugins"
DIST = WORKSPACE / ".temp" / "plugin-dist"
DOCS = WORKSPACE / ".build" / "docs"
GITEE = "https://gitee.com/qiuzongman/RuPix-Plugins/releases/download"
GITHUB = "https://github.com/zongmanqiu/RuPix-Plugins/releases/download"

# 随包进的"人读文件"：插件目录里放一份，用户装完能在 plugins/<id>/ 里直接看到。
# 宿主**不解析**它们（自述只有 manifest.json 一份），这里只为把文件带进去。
DOC_FILES = ("README.md", "LICENSE", "LICENSE.md", "LICENSE.txt", "NOTICE")

# 许可与源码位置说明：每枚 ZIP 必带一枚 `LICENSE-NOTICE.md`，内容是**两个事实**——
# 这份产物按什么许可、对应源码在哪个 tag 的哪个目录。
# ★ 2026-11-01 用户口径撤掉了"三年内书面提供源码"那套写法：我们是**开源项目，源码就在网上**，
# 那张书面要约卡是物理分发时代的遗留，我们没有需要"另行提供"的东西。名字也不再叫 SOURCE-OFFER。
# 它由本函数**生成**而不是仓里的一份文件 ⇒ 不存在"忘了放"，也不必手工同步第二份措辞。
GITEE_REPO = "https://gitee.com/qiuzongman/RuPix-Plugins"
GITHUB_REPO = "https://github.com/zongmanqiu/RuPix-Plugins"


def license_notice(pid: str, version: str, file_name: str) -> str:
    """Return the text of `LICENSE-NOTICE.md` packed into every plugin ZIP.

    Two facts, nothing else: the license covering this artifact, and where the
    source for exactly this version is published. No time-bound offer and no
    request procedure — the repository is public, so the source needs no offer.
    """
    tag = f"{pid}_{version}"
    return f"""# License and source for `{file_name}`

This package contains the plugin **{pid}**, version {version}.

## License

- The **plugin in this ZIP** is licensed under the **MIT License**; its full text
  ships next to this file as `LICENSE`. Keep that notice with any redistribution.
- The **source repository as a whole** is licensed under **AGPL-3.0**
  (`LICENSE` at the repository root). Third-party crates linked into this plugin
  are listed, with their licenses, in `THIRD-PARTY-NOTICES.md` at the repository
  root; the per-package list is generated by `python tools/check_licenses.py --list`.

## Source for this exact version

This is an open-source project, so there is nothing to request: the complete
corresponding source of this version is the published repository content at the
release tag `{tag}`, directory `plugins/{pid}/`.

- Gitee: {GITEE_REPO}/tree/{tag}/plugins/{pid}
- GitHub: {GITHUB_REPO}/tree/{tag}/plugins/{pid}

How to rebuild this plugin: `plugins/{pid}/build.ps1`, with the pipeline and
layout described in `docs/building.md` at the repository root.

This file states our licensing as we understand it; it is not a legal opinion.
"""


def third_party_notices(plugin_dir: Path) -> str | None:
    """Per-package license table for one plugin's ZIP, or `None` if it has no Rust deps.

    ★ Why this ships at all: every crate here is statically linked into `<id>.exe`,
    and the permissive licenses (MIT / Apache-2.0 / BSD / ...) ask that recipients
    get the license identification with the work. Pointing only at the repository
    root was the weak form of that; this table is generated from the same
    `cargo metadata` resolution the license gate checks, so it cannot drift from
    what actually got linked.
    """
    manifest = plugin_dir / "Cargo.toml"
    if not manifest.is_file():
        return None
    data = cargo_metadata(manifest)
    rows: dict[tuple[str, str], str] = {}
    for record in data.get("packages", []):
        if record.get("source") is None:
            continue  # 本仓自写的 crate（插件自己），不是第三方
        expr = record.get("license") or record.get("license_file") or "(none)"
        rows[(record["name"], record["version"])] = expr
    pid = plugin_dir.name
    lines = [
        f"# Third-party notices for `{pid}`",
        "",
        f"This plugin ships as one executable, `{pid}.exe`, built by statically linking",
        "the crates below. Each row is a package actually present in the resolved",
        "dependency graph of this build, read from `cargo metadata` — the same resolution",
        "`tools/check_licenses.py` gates, so this table and the gate cannot disagree.",
        "",
        "All of them carry redistribution-friendly licenses (MIT / Apache-2.0 / BSD /",
        "ISC / Zlib / Unlicense / BSL-1.0 / CC0-1.0 / Unicode-3.0). The license text and",
        "source for any row live upstream: `https://crates.io/crates/<name>/<version>`",
        "links onward to the repository named in that crate's `Cargo.toml`.",
        "",
        "Repository-wide policy, the accepted license families, and the rules for adding",
        "a dependency live in `THIRD-PARTY-NOTICES.md` at the repository root; the",
        "machine-readable list for all plugins is `python tools/check_licenses.py --list`.",
        "",
        "| package | version | license (SPDX) |",
        "|---|---:|---|",
    ]
    for (name, version), expr in sorted(rows.items()):
        lines.append(f"| `{name}` | {version} | {expr} |")
    lines += ["", f"{len(rows)} packages.", ""]
    return "\n".join(lines)


def fail(msg: str) -> int:
    print(f" [x] {msg}")
    return 1


# ZIP 里每个条目的时间戳钉死成这一格 ⇒ **包字节是内容的纯函数**。
# 实测不过这么做会怎样：用文件真实 mtime + `writestr` 的当前时间，同样内容重打一次包，
# `sha256` 就变（`e4b855a6…` → `85497a25…`），于是"清单里的 sha"变成"哪一刻打的包"的函数，
# 而不是"包里有啥"的函数——上传的资产与清单必须同刻对齐，否则宿主判校验失败。
ZIP_FIXED_DATE = (1980, 1, 1, 0, 0, 0)


def add_entry(z: zipfile.ZipFile, arcname: str, data: bytes) -> None:
    info = zipfile.ZipInfo(arcname, date_time=ZIP_FIXED_DATE)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    z.writestr(info, data)


def main() -> int:
    DOCS.mkdir(parents=True, exist_ok=True)
    entries = []
    for src in sorted(p for p in PLUGINS.iterdir() if p.is_dir()):
        manifest = src / "manifest.json"
        if not manifest.is_file():
            continue
        try:
            meta = json.loads(manifest.read_text(encoding="utf-8-sig"))
        except Exception as e:
            return fail(f"{manifest}: {e}")
        pid = meta.get("id")
        ver = meta.get("version")
        payload = DIST / str(pid)
        if not payload.is_dir():
            print(f"skip {pid}: no built payload at {payload}")
            continue
        if not (payload / "manifest.json").is_file():
            return fail(f"{payload}: missing manifest.json")

        file_name = f"{pid}_{ver}.zip"
        out_zip = DOCS / file_name
        with zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED) as z:
            for p in sorted(payload.rglob("*")):
                if p.is_file():
                    add_entry(z, p.relative_to(payload).as_posix(), p.read_bytes())
            for doc in DOC_FILES:
                f = src / doc
                if f.is_file() and not (payload / doc).is_file():
                    add_entry(z, doc, f.read_bytes())
            # 许可与源码位置：每枚 ZIP 必带，内容由 `license_notice()` 现生成。
            add_entry(z, "LICENSE-NOTICE.md", license_notice(str(pid), str(ver), file_name).encode("utf-8"))
            # 逐包许可表：静态链接进 exe 的第三方 crate，许可识别要随作品一起到用户手里。
            notices = third_party_notices(src)
            if notices is None:
                print(f"  note: {pid} 没有 Cargo.toml（纯资源插件）⇒ 不带逐包许可表")
            else:
                add_entry(z, "THIRD-PARTY-NOTICES.md", notices.encode("utf-8"))
        data = out_zip.read_bytes()
        tag = f"{pid}_{ver}"
        entries.append(
            {
                "id": pid,
                "name": meta.get("name", pid),
                "version": ver,
                "protocol": meta.get("protocol", 1),
                "min_host": meta.get("min_host", ""),
                "kind": meta.get("kind", "command"),
                "description": meta.get("description", ""),
                "capabilities": meta.get("capabilities", []),
                "released": meta.get("released", ""),
                "author": meta.get("author", "RuPix"),
                "license": meta.get("license", "MIT"),
                "file": file_name,
                "size": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
                "gitee": f"{GITEE}/{tag}/{file_name}",
                "github": f"{GITHUB}/{tag}/{file_name}",
            }
        )
        print(f"packed {pid} -> {out_zip}")

    text = json.dumps(entries, ensure_ascii=False, indent=2) + "\n"
    # `newline="\n"` 是刻意的：Windows 上 `write_text` 默认会把 `\n` 翻成 `\r\n`，
    # 而 `.gitattributes` 钉了 `*.json text eol=lf`——落盘用 CRLF 的话磁盘与库内字节不一致，
    # 每次 `git add` 都刷一排换行警告（宿主侧同一个坑记在插件仓 docs/pitfalls.md P8）。
    (DOCS / "plugins.json").write_text(text, encoding="utf-8", newline="\n")
    (ROOT / "plugins.json").write_text(text, encoding="utf-8", newline="\n")
    old_index = ROOT / "index.json"
    if old_index.is_file():
        old_index.unlink()
    print(f"plugins.json: {len(entries)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
